-- PostgreSQL schema for Supabase. The PHP API and chat service connect using
-- the server-side database credentials; no database credentials belong in the browser.

CREATE TABLE public.users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('patient', 'doctor', 'pharmacist', 'admin')),
    phone VARCHAR(30),
    is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    account_status TEXT NOT NULL DEFAULT 'approved'
        CHECK (account_status IN ('pending', 'approved', 'rejected', 'blocked')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login TIMESTAMP NULL,
    status_changed_at TIMESTAMP NULL,
    status_changed_by INTEGER REFERENCES public.users(user_id) ON DELETE SET NULL
);

CREATE INDEX idx_users_role ON public.users(role);
CREATE INDEX idx_users_account_status ON public.users(account_status);
CREATE INDEX idx_users_role_status ON public.users(role, account_status);

CREATE TABLE public.patients (
    patient_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL UNIQUE REFERENCES public.users(user_id) ON DELETE CASCADE,
    date_of_birth DATE,
    gender TEXT CHECK (gender IN ('male', 'female', 'other')),
    address TEXT,
    medical_history_summary TEXT,
    emergency_contact VARCHAR(100)
);

CREATE TABLE public.doctors (
    doctor_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL UNIQUE REFERENCES public.users(user_id) ON DELETE CASCADE,
    license_number VARCHAR(50) NOT NULL UNIQUE,
    specialisation VARCHAR(100),
    affiliated_institution VARCHAR(150),
    is_available SMALLINT NOT NULL DEFAULT 1 CHECK (is_available IN (0, 1))
);

CREATE TABLE public.pharmacists (
    pharmacist_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL UNIQUE REFERENCES public.users(user_id) ON DELETE CASCADE,
    pharmacy_name VARCHAR(150) NOT NULL,
    pharmacy_registration_number VARCHAR(50) NOT NULL UNIQUE,
    pharmacy_address TEXT NOT NULL
);

CREATE TABLE public.consultations (
    consultation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES public.patients(patient_id) ON DELETE CASCADE,
    doctor_id INTEGER REFERENCES public.doctors(doctor_id) ON DELETE SET NULL,
    submitted_symptoms TEXT NOT NULL,
    triage_score INTEGER DEFAULT 0,
    triage_recommendation VARCHAR(50),
    communication_mode TEXT NOT NULL DEFAULT 'chat' CHECK (communication_mode IN ('chat', 'video')),
    diagnosis_notes TEXT,
    status TEXT NOT NULL DEFAULT 'queued'
        CHECK (status IN ('queued', 'assigned', 'in_progress', 'prescribed', 'referred', 'completed', 'cancelled')),
    requested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMP NULL,
    closed_at TIMESTAMP NULL
);

CREATE INDEX idx_consultations_status ON public.consultations(status);
CREATE INDEX idx_consultations_patient ON public.consultations(patient_id);
CREATE INDEX idx_consultations_doctor ON public.consultations(doctor_id);

CREATE TABLE public.prescriptions (
    prescription_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescription_uid VARCHAR(40) NOT NULL UNIQUE,
    consultation_id INTEGER NOT NULL REFERENCES public.consultations(consultation_id) ON DELETE CASCADE,
    patient_id INTEGER NOT NULL REFERENCES public.patients(patient_id) ON DELETE CASCADE,
    doctor_id INTEGER NOT NULL REFERENCES public.doctors(doctor_id) ON DELETE CASCADE,
    pharmacist_id INTEGER NOT NULL REFERENCES public.pharmacists(pharmacist_id) ON DELETE CASCADE,
    medication_name VARCHAR(200) NOT NULL,
    dosage VARCHAR(100) NOT NULL,
    frequency VARCHAR(100) NOT NULL,
    duration VARCHAR(100) NOT NULL,
    instructions TEXT,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'dispensed', 'unavailable', 'cancelled')),
    issued_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    dispensed_at TIMESTAMP NULL
);

CREATE INDEX idx_prescriptions_status ON public.prescriptions(status);

CREATE TABLE public.health_records (
    record_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES public.patients(patient_id) ON DELETE CASCADE,
    consultation_id INTEGER REFERENCES public.consultations(consultation_id) ON DELETE SET NULL,
    doctor_id INTEGER REFERENCES public.doctors(doctor_id) ON DELETE SET NULL,
    record_type TEXT NOT NULL DEFAULT 'consultation_note'
        CHECK (record_type IN ('consultation_note', 'diagnosis', 'vital_signs', 'allergy', 'chronic_condition', 'other')),
    title VARCHAR(150) NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_health_records_patient ON public.health_records(patient_id);

CREATE TABLE public.referrals (
    referral_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultation_id INTEGER NOT NULL REFERENCES public.consultations(consultation_id) ON DELETE CASCADE,
    patient_id INTEGER NOT NULL REFERENCES public.patients(patient_id) ON DELETE CASCADE,
    doctor_id INTEGER NOT NULL REFERENCES public.doctors(doctor_id) ON DELETE CASCADE,
    clinic_name VARCHAR(150) NOT NULL,
    clinic_address TEXT NOT NULL,
    clinic_contact VARCHAR(50),
    appointment_date DATE NOT NULL,
    appointment_time TIME NOT NULL,
    referral_reason TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'scheduled'
        CHECK (status IN ('scheduled', 'attended', 'missed', 'cancelled')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.notifications (
    notification_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    title VARCHAR(150) NOT NULL,
    message TEXT NOT NULL,
    type TEXT NOT NULL CHECK (type IN ('consultation', 'prescription', 'referral', 'system')),
    related_id INTEGER,
    is_read SMALLINT NOT NULL DEFAULT 0 CHECK (is_read IN (0, 1)),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_notifications_user_unread ON public.notifications(user_id, is_read);

CREATE TABLE public.chat_messages (
    message_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultation_id INTEGER NOT NULL REFERENCES public.consultations(consultation_id) ON DELETE CASCADE,
    sender_user_id INTEGER NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    sender_role TEXT NOT NULL CHECK (sender_role IN ('patient', 'doctor')),
    message_text TEXT NOT NULL,
    sent_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_chat_messages_consultation ON public.chat_messages(consultation_id);

CREATE TABLE public.audit_log (
    audit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id INTEGER REFERENCES public.users(user_id) ON DELETE SET NULL,
    actor_role VARCHAR(20),
    action VARCHAR(80) NOT NULL,
    entity_type VARCHAR(40) NOT NULL,
    entity_id INTEGER,
    details TEXT,
    ip_address VARCHAR(45),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_audit_log_action ON public.audit_log(action);
CREATE INDEX idx_audit_log_entity ON public.audit_log(entity_type, entity_id);

CREATE TABLE public.allergies (
    allergy_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES public.patients(patient_id) ON DELETE CASCADE,
    allergen VARCHAR(150) NOT NULL,
    severity TEXT NOT NULL DEFAULT 'mild' CHECK (severity IN ('mild', 'moderate', 'severe')),
    reaction TEXT,
    noted_on DATE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_allergies_patient ON public.allergies(patient_id);

CREATE TABLE public.chronic_conditions (
    condition_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES public.patients(patient_id) ON DELETE CASCADE,
    condition_name VARCHAR(150) NOT NULL,
    diagnosed_date DATE,
    notes TEXT,
    is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_chronic_conditions_patient ON public.chronic_conditions(patient_id);

CREATE TABLE public.refill_requests (
    request_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescription_id INTEGER NOT NULL REFERENCES public.prescriptions(prescription_id) ON DELETE CASCADE,
    patient_id INTEGER NOT NULL REFERENCES public.patients(patient_id) ON DELETE CASCADE,
    reviewed_by_doctor_id INTEGER REFERENCES public.doctors(doctor_id) ON DELETE SET NULL,
    note TEXT,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'denied', 'dispensed')),
    requested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMP NULL
);

CREATE INDEX idx_refill_requests_status ON public.refill_requests(status);

CREATE TABLE public.drugs (
    drug_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    strength VARCHAR(50),
    form TEXT NOT NULL DEFAULT 'tablet'
        CHECK (form IN ('tablet', 'capsule', 'syrup', 'injection', 'cream', 'drops', 'inhaler', 'other')),
    common_dosage VARCHAR(100),
    common_frequency VARCHAR(100),
    notes TEXT
);

CREATE INDEX idx_drugs_name ON public.drugs(name);

